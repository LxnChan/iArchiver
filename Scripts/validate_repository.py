#!/usr/bin/env python3
"""Structural checks; deliberately does not label syntax parsing as an iOS build."""
from __future__ import annotations
import hashlib
import json
import pathlib
import plistlib
import re
import struct
import xml.etree.ElementTree as ET
from bootstrap import ROOT


def validate():
    for path in list((ROOT / "Config").glob("*.plist")) + list((ROOT / "Resources").rglob("*.xcprivacy")):
        with path.open("rb") as stream:
            plistlib.load(stream)
    languages = {}
    for language in ["en", "zh-Hans"]:
        text = (ROOT / "Resources" / f"{language}.lproj" / "Localizable.strings").read_text(encoding="utf-8")
        pairs = re.findall(r'("(?:[^"\\]|\\.)*")\s*=\s*("(?:[^"\\]|\\.)*")\s*;', text)
        languages[language] = {json.loads(key): json.loads(value) for key, value in pairs}
        assert len(pairs) == len(languages[language]), f"Duplicate keys: {language}"
        assert all(languages[language].values()), f"Empty translation: {language}"
    assert languages["en"].keys() == languages["zh-Hans"].keys(), "Translation key mismatch"

    from tree_sitter import Language, Parser
    import tree_sitter_swift
    from openstep_parser import OpenStepDecoder
    parser = Parser(Language(tree_sitter_swift.language()))
    swift = sorted((ROOT / "Sources").rglob("*.swift")) + sorted((ROOT / "Tests").rglob("*.swift")) + [ROOT / "Package.swift"]
    for path in swift:
        data = path.read_bytes()
        tree = parser.parse(data)
        assert not tree.root_node.has_error, f"Swift syntax error: {path.relative_to(ROOT)}"
        keys = re.findall(r'"((?:action|app|empty|encoding|password|preview|sort|field|settings|create|task|error|file|queue|background|conflict)\.[A-Za-z][A-Za-z0-9.]*)"', data.decode())
        if "Tests" not in path.parts:
            for key in keys:
                assert key in languages["en"], f"Missing localization {key}: {path}"
    with (ROOT / "iArchiver.xcodeproj" / "project.pbxproj").open(encoding="utf-8") as stream:
        project = OpenStepDecoder.ParseFromFile(stream)
    objects = project["objects"]
    for reference in objects.values():
        if reference.get("isa") != "PBXFileReference" or reference.get("sourceTree") == "BUILT_PRODUCTS_DIR":
            continue
        path = reference.get("path", "")
        if path.startswith("Build/"):
            continue  # Generated by the Mac XCFramework build.
        assert (ROOT / path).exists(), f"Missing Xcode file: {path}"
    sources = {reference["path"] for reference in objects.values() if reference.get("lastKnownFileType") == "sourcecode.swift" and reference["path"].startswith("Sources/")}
    expected = {path.relative_to(ROOT).as_posix() for path in (ROOT / "Sources").rglob("*.swift")}
    assert sources == expected, "Regenerate the Xcode project after adding Swift files"
    for target in [item for item in objects.values() if item.get("productType") == "com.apple.product-type.application"]:
        resources = []
        for phase_id in target["buildPhases"]:
            phase = objects[phase_id]
            if phase["isa"] == "PBXResourcesBuildPhase":
                resources += [objects[objects[item]["fileRef"]].get("path", "") for item in phase["files"]]
        assert ("Resources/UnRARLicense.txt" in resources) == (target["name"] == "iArchiver-Sideload")
    schemes = list((ROOT / "iArchiver.xcodeproj" / "xcshareddata" / "xcschemes").glob("*.xcscheme"))
    assert len(schemes) == 2
    for path in schemes:
        ET.parse(path)
    icon = (ROOT / "Resources" / "Assets.xcassets" / "AppIcon.appiconset" / "AppIcon.png").read_bytes()
    width, height, depth, mode = struct.unpack(">IIBB", icon[16:26])
    assert (width, height, depth, mode) == (1024, 1024, 8, 2), "App icon must be opaque RGB 1024"
    lock = json.loads((ROOT / "Dependencies.lock.json").read_text(encoding="utf-8"))
    for item in lock["dependencies"]:
        assert re.fullmatch("[a-f0-9]{64}", item["sha256"])
        if "vendor_archive" in item:
            assert hashlib.sha256((ROOT / item["vendor_archive"]).read_bytes()).hexdigest() == item["sha256"]
    privacy = plistlib.loads((ROOT / "Resources" / "PrivacyInfo.xcprivacy").read_bytes())
    assert privacy["NSPrivacyTracking"] is False and privacy["NSPrivacyCollectedDataTypes"] == []
    print(f"PASS: {len(swift)} Swift syntax trees, {len(sources)} app sources, two schemes, bilingual strings, plists, RGB icon, pinned vendor hash.")
    print("Swift type checking, SDK availability, native Apple linking and UI behavior require the Mac checks.")


if __name__ == "__main__":
    validate()
